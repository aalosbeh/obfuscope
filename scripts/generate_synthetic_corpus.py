"""
Generate a synthetic, non-malicious placeholder corpus for smoke-testing the
ObfuScope pipeline mechanics (feature extraction -> experiment grid ->
aggregation -> plots -> HTC manifest) without touching any real malware.

Every emitted ``.c`` file is a small fabricated snippet -- no real behaviour,
no functioning payload, nothing that compiles into anything harmful -- built
only to exercise the regex-based static feature extractor in
``obfuscope.features`` and the path-based labelling in ``obfuscope.labels``.
API-bucket and obfuscation-indicator tokens are embedded via ``_stub``-suffixed
fake calls so the feature vectors are non-degenerate without any of the
snippets being real or executable.

This does NOT replace the actual obfuscated-malware corpus and produces no
scientifically meaningful results -- it only proves the pipeline's plumbing is
correct end-to-end (see README.md "Data & safety").

Usage
-----
    python3 scripts/generate_synthetic_corpus.py --out data/corpus \
        --families 8 --samples-per-family 3 --seed 0
"""
