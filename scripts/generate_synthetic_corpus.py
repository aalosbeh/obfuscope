def _rand_ident(rng: random.Random, n: int = 8) -> str:
    letters = "abcdefghijklmnopqrstuvwxyz"
    return rng.choice(letters) + "".join(rng.choice(letters + "0123456789") for _ in range(n - 1))


def render_c_source(rng: random.Random, technique: str, subname: str, tag: str) -> str:
    """Fabricate one small, non-functional, clearly-marked C snippet."""
    flavor = FLAVOR_TOKENS[technique]
    n_funcs = rng.randint(2, 5)
    n_branches = rng.randint(1, 4)
    xor_key = rng.randint(1, 255)
    magic = rng.randint(0x1000, 0xFFFF)

    funcs = []
    for i in range(n_funcs):
        fname = f"{rng.choice(flavor)}_{_rand_ident(rng, 5)}"
        body_lines = [f"    int {_rand_ident(rng, 6)} = {rng.randint(0, 999)};"]
        for _ in range(n_branches):
            if rng.random() < 0.5:
                body_lines.append(f"    if (0) {{ {rng.choice(flavor)}(); }}")
            else:
                body_lines.append(
                    f"    for (int k = 0; k < {rng.randint(1, 9)}; k++) {{ "
                    f"{_rand_ident(rng, 5)} ^= 0x{xor_key:02X}; }}")
        body_lines.append(f"    /* calls: {rng.choice(flavor)}_stub() */")
        body_lines.append(f"    return {magic} & 0xFF;")
        funcs.append(
            f"int {fname}(void) {{\n" + "\n".join(body_lines) + "\n}\n")

    header = (
        SYNTHETIC_BANNER
        + f"/* technique={technique} sub_variant={subname} sample={tag} */\n"
        + "#include <stdint.h>\n\n"
        + f"static const char *SYNTH_TAG = \"{tag}::{subname}\";\n\n"
    )
    return header + "\n".join(funcs)


def _family_dir_name(rng: random.Random, family: str) -> str:
    md5_like = "".join(rng.choice("0123456789abcdef") for _ in range(32))
    ext = rng.choice(["exe", "bat", "vbs", "js", "ps1"])
    return f"{md5_like}_{family}.{ext}"


def generate(out_root: str, n_families: int, samples_per_family: int, seed: int,
             cohort: str = "synthetic_cohort", verbose: bool = True) -> int:
    rng = random.Random(seed)
    cohort_dir = os.path.join(out_root, cohort)
    os.makedirs(cohort_dir, exist_ok=True)
    n_files = 0
    for fam_idx in range(n_families):
        family = f"SyntheticFamily{chr(ord('A') + fam_idx)}"
        for s in range(samples_per_family):
            sample_dir_name = _family_dir_name(rng, family)
            sample_dir = os.path.join(cohort_dir, sample_dir_name)
            tag = f"{family}-{s}"
            for technique in TECHNIQUE_DIRS:
                tech_dir = os.path.join(sample_dir, technique)
                os.makedirs(tech_dir, exist_ok=True)
                for fname in TECHNIQUE_FILES[technique]:
                    subname = os.path.splitext(fname)[0]
                    src = render_c_source(rng, technique, subname, tag)
                    with open(os.path.join(tech_dir, fname), "w") as fh:
                        fh.write(src)
                    n_files += 1
    if verbose:
        print(f"[synthetic-corpus] wrote {n_files} .c files across "
              f"{n_families * samples_per_family} sample dirs -> {cohort_dir}",
              file=sys.stderr)
    return n_files


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default="data/corpus", help="corpus root to write into")
    ap.add_argument("--families", type=int, default=8, help="number of synthetic malware families")
    ap.add_argument("--samples-per-family", type=int, default=3)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--cohort", default="synthetic_cohort")
    args = ap.parse_args(argv)
    generate(args.out, args.families, args.samples_per_family, args.seed, args.cohort)


if __name__ == "__main__":
    main()
