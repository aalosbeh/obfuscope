def tt(s: str) -> str:
    return r"\code{" + s.replace("_", r"\_") + "}"


def esc(s: str) -> str:
    return s.replace("_", r"\_").replace("%", r"\%")


class Table:
    """Collects the ledger keys a table uses and writes the .tex file."""

    def __init__(self, fname: str, label: str, caption: str, where: str):
        self.fname, self.label, self.caption, self.where = fname, label, caption, where
        self.keys: List[str] = []
        self.sources: List[str] = []

    def d(self, key: str) -> str:
        if key not in LEDGER:
            raise KeyError(f"{self.fname}: ledger key missing: {key}")
        if key not in self.keys:
            self.keys.append(key)
        return LEDGER[key]["display"]

    def v(self, key: str):
        if key not in LEDGER:
            raise KeyError(f"{self.fname}: ledger key missing: {key}")
        if key not in self.keys:
            self.keys.append(key)
        return LEDGER[key]["value"]

    def has(self, key: str) -> bool:
        return key in LEDGER

    def write(self, body: str) -> str:
        out_dir = ART if self.where == "article" else SUP
        os.makedirs(out_dir, exist_ok=True)
        head = ("% AUTO-GENERATED by code/obfuscope-corrected/scripts/manuscript_v3/make_tables.py\n"
                "% from _work/ledger/ledger.json; do not edit by hand (re-run the script).\n"
                f"% ledger keys used: {len(self.keys)} (all listed in MANIFEST.txt)\n")
        v3 = [k for k in self.keys
              if LEDGER[k]["source"].startswith("results/v3") or "LEDGER-COMPUTED" in LEDGER[k]["note"]]
        if v3:
            head += "% v3 (revision analyses or ledger-computed): " + ", ".join(v3[:12]) + (
                f", ... ({len(v3)} keys)" if len(v3) > 12 else "") + "\n"
        path = os.path.join(out_dir, self.fname)
        with open(path, "w") as fh:
            fh.write(head + body)
        return path


MANIFEST: Dict[str, List[Table]] = {"article": [], "supplement": []}


def float_env(t: Table, inner: str, notes: Optional[str] = None, size: str = r"\footnotesize",
              sep: str = "4pt", placement: str = "tbp") -> str:
    s = [f"\\begin{{table}}[{placement}]",
         f"\\caption{{{t.caption}}}",
         f"\\label{{{t.label}}}",
         f"{size}",
         f"\\setlength{{\\tabcolsep}}{{{sep}}}",
         inner.rstrip()]
    if notes:
        s.append(r"\par\begin{minipage}{\textwidth}\scriptsize " + notes + r"\end{minipage}")
    s.append(r"\end{table}")
    return "\n".join(s) + "\n"


def tabstar(colspec: str, rows: Sequence[str]) -> str:
    """tabular* filling \\textwidth; colspec without the outer @{} (first column left)."""
    first, rest = colspec[0], colspec[1:]
    return ("\\begin{tabular*}{\\textwidth}{@{}" + first + "@{\\extracolsep{\\fill}}" + rest + "@{}}\n"
            + "\n".join(rows) + "\n\\end{tabular*}")


def tabx(colspec: str, rows: Sequence[str]) -> str:
    return ("\\begin{tabularx}{\\textwidth}{@{}" + colspec + "@{}}\n" + "\n".join(rows) + "\n\\end{tabularx}")


X = r">{\raggedright\arraybackslash}X"


def finish(t: Table, inner: str, notes: Optional[str] = None, **kw) -> None:
    t.write(float_env(t, inner, notes, **kw))
    MANIFEST[t.where].append(t)


def check_name(s: str) -> str:
    return {"1_distinct_ratio": "1", "1b_input_dependence": "1b", "2_constant_features": "2",
            "3_cross_group_duplicates": "3", "4_feature_ceiling": "4a", "4b_headroom": "4b",
            "5_permuted_labels": "5", "6_cross_class_duplicates": "6"}.get(s, s.split("_")[0])


