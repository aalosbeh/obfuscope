def _pair(t: Table, prefix: str, a: str, b: str, fields: Sequence[str]):
    """Return field displays for a minus b, flipping orientation when the file stores b minus a."""
    k1, k2 = f"{prefix}.{a}_vs_{b}", f"{prefix}.{b}_vs_{a}"
    if f"{k1}.mean_diff" in LEDGER:
        return {f: t.d(f"{k1}.{f}") for f in fields}
    out = {}
    for f in fields:
        if f == "mean_diff":
            v = -float(t.v(f"{k2}.mean_diff"))
            s = f"{abs(v):.4f}"
            out[f] = f"$-{s}$" if v < 0 and float(s) != 0 else s
        elif f == "wtl":
            w, ti, lo = t.d(f"{k2}.wtl").split("/")
            out[f] = f"{lo}/{ti}/{w}"
        else:
            out[f] = t.d(f"{k2}.{f}")
    return out


