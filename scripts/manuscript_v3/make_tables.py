def _bib_cite(surname: str, year: str, title_word: str, fallback: str) -> str:
    """\\citet{key} when references.bib holds a matching entry, otherwise plain text."""
    bib = os.path.join(TEX, "references.bib")
    try:
        txt = open(bib).read()
    except OSError:
        return fallback
    for m in re.finditer(r"@\w+\s*\{\s*([^,\s]+)\s*,(.*?)\n\}", txt, re.S):
        key, body = m.group(1), m.group(2)
        au = re.search(r"author\s*=\s*[{\"](.*?)[}\"]\s*,", body, re.S)
        yr = re.search(r"year\s*=\s*[{\"]?(\d{4})", body)
        ti = re.search(r"title\s*=\s*[{\"](.*?)[}\"]\s*,", body, re.S)
        if au and yr and ti and surname.lower() in au.group(1).lower() and yr.group(1) == year \
                and title_word.lower() in ti.group(1).lower():
            return r"\citet{" + key + "}"
    return fallback


