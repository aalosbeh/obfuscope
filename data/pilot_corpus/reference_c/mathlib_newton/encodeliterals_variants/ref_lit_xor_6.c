#include <stdio.h>
static double f(double x) { return x * x * x - 2.0 * x - 5.0; }
static double fp(double x) { return 3.0 * x * x - 2.0; }
int main(void) {
    double x = 2.0;
    int iters = (0x60E3F5BB ^ 0x60E3F5BB);
    while (iters < (0x1CB1CE5F ^ 0x1CB1CE1F)) {
        double d = f(x) / fp(x);
        x -= d;
        iters++;
        if (d < 1e-12 && d > -1e-12) break;
    }
    printf("%.6f %d\n", x, iters);
    return (0xF7B1DD4 ^ 0xF7B1DD4);
}
