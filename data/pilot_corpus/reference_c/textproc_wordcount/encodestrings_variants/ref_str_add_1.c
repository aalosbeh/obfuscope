#include <stdio.h>
#include <string.h>

static char dec_d3fb_buf[4][256];
static int dec_d3fb_slot = 0;
static const char *dec_d3fb(const unsigned char *enc, int n, int key) {
    int s = dec_d3fb_slot++ % 4;
    char *out = dec_d3fb_buf[s];
    for (int i = 0; i < n && i < 255; i++) out[i] = (char)(enc[i] - key);
    out[n < 255 ? n : 255] = '\0';
    return out;
}

int main(void) {
    const char *text = dec_d3fb((const unsigned char[]){0x11, 0x05, 0x02, 0xBD, 0x0E, 0x12, 0x06, 0x00, 0x08, 0xBD, 0xFF, 0x0F, 0x0C, 0x14, 0x0B, 0xBD, 0x03, 0x0C, 0x15, 0xBD, 0x07, 0x12, 0x0A, 0x0D, 0x10, 0xBD, 0x0C, 0x13, 0x02, 0x0F, 0xBD, 0x11, 0x05, 0x02, 0xBD, 0x09, 0xFE, 0x17, 0x16, 0xBD, 0x01, 0x0C, 0x04, 0xBD, 0xFE, 0x0B, 0x01, 0xBD, 0x11, 0x05, 0x02, 0xBD, 0x01, 0x0C, 0x04, 0xBD, 0x10, 0x09, 0x02, 0x02, 0x0D, 0x10}, 62, 157);
    int words = 0, in_word = 0, letters = 0;
    for (const char *p = text; *p; p++) {
        if (*p == ' ') { in_word = 0; }
        else { if (!in_word) { words++; in_word = 1; } letters++; }
    }
    printf(dec_d3fb((const unsigned char[]){0xC2, 0x01, 0xBD, 0xC2, 0x01, 0xBD, 0xC2, 0x17, 0x12, 0xA7}, 10, 157), words, letters, strlen(text));
    return 0;
}
