#include <stdio.h>
#include <string.h>

static char dec_4b30_buf[4][256];
static int dec_4b30_slot = 0;
static const char *dec_4b30(const unsigned char *enc, int n, int key) {
    int s = dec_4b30_slot++ % 4;
    char *out = dec_4b30_buf[s];
    for (int i = 0; i < n && i < 255; i++) out[i] = (char)(enc[i] ^ key);
    out[n < 255 ? n : 255] = '\0';
    return out;
}

int main(void) {
    const char *text = dec_4b30((const unsigned char[]){0x95, 0x89, 0x84, 0xC1, 0x90, 0x94, 0x88, 0x82, 0x8A, 0xC1, 0x83, 0x93, 0x8E, 0x96, 0x8F, 0xC1, 0x87, 0x8E, 0x99, 0xC1, 0x8B, 0x94, 0x8C, 0x91, 0x92, 0xC1, 0x8E, 0x97, 0x84, 0x93, 0xC1, 0x95, 0x89, 0x84, 0xC1, 0x8D, 0x80, 0x9B, 0x98, 0xC1, 0x85, 0x8E, 0x86, 0xC1, 0x80, 0x8F, 0x85, 0xC1, 0x95, 0x89, 0x84, 0xC1, 0x85, 0x8E, 0x86, 0xC1, 0x92, 0x8D, 0x84, 0x84, 0x91, 0x92}, 62, 225);
    int words = 0, in_word = 0, letters = 0;
    for (const char *p = text; *p; p++) {
        if (*p == ' ') { in_word = 0; }
        else { if (!in_word) { words++; in_word = 1; } letters++; }
    }
    printf(dec_4b30((const unsigned char[]){0xC4, 0x85, 0xC1, 0xC4, 0x85, 0xC1, 0xC4, 0x9B, 0x94, 0xEB}, 10, 225), words, letters, strlen(text));
    return 0;
}
