#include <stdio.h>
#include <string.h>

static char dec_5df4_buf[4][256];
static int dec_5df4_slot = 0;
static const char *dec_5df4(const unsigned char *enc, int n, int key) {
    int s = dec_5df4_slot++ % 4;
    char *out = dec_5df4_buf[s];
    for (int i = 0; i < n && i < 255; i++) out[i] = (char)(enc[i] - key);
    out[n < 255 ? n : 255] = '\0';
    return out;
}

int main(void) {
    const char *text = dec_5df4((const unsigned char[]){0x13, 0x07, 0x04, 0xBF, 0x10, 0x14, 0x08, 0x02, 0x0A, 0xBF, 0x01, 0x11, 0x0E, 0x16, 0x0D, 0xBF, 0x05, 0x0E, 0x17, 0xBF, 0x09, 0x14, 0x0C, 0x0F, 0x12, 0xBF, 0x0E, 0x15, 0x04, 0x11, 0xBF, 0x13, 0x07, 0x04, 0xBF, 0x0B, 0x00, 0x19, 0x18, 0xBF, 0x03, 0x0E, 0x06, 0xBF, 0x00, 0x0D, 0x03, 0xBF, 0x13, 0x07, 0x04, 0xBF, 0x03, 0x0E, 0x06, 0xBF, 0x12, 0x0B, 0x04, 0x04, 0x0F, 0x12}, 62, 159);
    int words = 0, in_word = 0, letters = 0;
    for (const char *p = text; *p; p++) {
        if (*p == ' ') { in_word = 0; }
        else { if (!in_word) { words++; in_word = 1; } letters++; }
    }
    printf(dec_5df4((const unsigned char[]){0xC4, 0x03, 0xBF, 0xC4, 0x03, 0xBF, 0xC4, 0x19, 0x14, 0xA9}, 10, 159), words, letters, strlen(text));
    return 0;
}
