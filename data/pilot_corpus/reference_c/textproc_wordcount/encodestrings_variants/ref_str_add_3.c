#include <stdio.h>
#include <string.h>

static char dec_3608_buf[4][256];
static int dec_3608_slot = 0;
static const char *dec_3608(const unsigned char *enc, int n, int key) {
    int s = dec_3608_slot++ % 4;
    char *out = dec_3608_buf[s];
    for (int i = 0; i < n && i < 255; i++) out[i] = (char)(enc[i] - key);
    out[n < 255 ? n : 255] = '\0';
    return out;
}

int main(void) {
    const char *text = dec_3608((const unsigned char[]){0xF0, 0xE4, 0xE1, 0x9C, 0xED, 0xF1, 0xE5, 0xDF, 0xE7, 0x9C, 0xDE, 0xEE, 0xEB, 0xF3, 0xEA, 0x9C, 0xE2, 0xEB, 0xF4, 0x9C, 0xE6, 0xF1, 0xE9, 0xEC, 0xEF, 0x9C, 0xEB, 0xF2, 0xE1, 0xEE, 0x9C, 0xF0, 0xE4, 0xE1, 0x9C, 0xE8, 0xDD, 0xF6, 0xF5, 0x9C, 0xE0, 0xEB, 0xE3, 0x9C, 0xDD, 0xEA, 0xE0, 0x9C, 0xF0, 0xE4, 0xE1, 0x9C, 0xE0, 0xEB, 0xE3, 0x9C, 0xEF, 0xE8, 0xE1, 0xE1, 0xEC, 0xEF}, 62, 124);
    int words = 0, in_word = 0, letters = 0;
    for (const char *p = text; *p; p++) {
        if (*p == ' ') { in_word = 0; }
        else { if (!in_word) { words++; in_word = 1; } letters++; }
    }
    printf(dec_3608((const unsigned char[]){0xA1, 0xE0, 0x9C, 0xA1, 0xE0, 0x9C, 0xA1, 0xF6, 0xF1, 0x86}, 10, 124), words, letters, strlen(text));
    return 0;
}
