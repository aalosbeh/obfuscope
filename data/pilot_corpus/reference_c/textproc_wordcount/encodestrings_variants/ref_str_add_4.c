static char dec_912b_buf[4][256];
static int dec_912b_slot = 0;
static const char *dec_912b(const unsigned char *enc, int n, int key) {
    int s = dec_912b_slot++ % 4;
    char *out = dec_912b_buf[s];
    for (int i = 0; i < n && i < 255; i++) out[i] = (char)(enc[i] - key);
    out[n < 255 ? n : 255] = '\0';
    return out;
}

