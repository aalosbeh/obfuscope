#include <stdio.h>
#include <string.h>

static char dec_44fa_buf[4][256];
static int dec_44fa_slot = 0;
static const char *dec_44fa(const unsigned char *enc, int n, int key) {
    int s = dec_44fa_slot++ % 4;
    char *out = dec_44fa_buf[s];
    for (int i = 0; i < n && i < 255; i++) out[i] = (char)(enc[i] - key);
    out[n < 255 ? n : 255] = '\0';
    return out;
}

int main(void) {
    const char *text = dec_44fa((const unsigned char[]){0x20, 0x14, 0x11, 0xCC, 0x1D, 0x21, 0x15, 0x0F, 0x17, 0xCC, 0x0E, 0x1E, 0x1B, 0x23, 0x1A, 0xCC, 0x12, 0x1B, 0x24, 0xCC, 0x16, 0x21, 0x19, 0x1C, 0x1F, 0xCC, 0x1B, 0x22, 0x11, 0x1E, 0xCC, 0x20, 0x14, 0x11, 0xCC, 0x18, 0x0D, 0x26, 0x25, 0xCC, 0x10, 0x1B, 0x13, 0xCC, 0x0D, 0x1A, 0x10, 0xCC, 0x20, 0x14, 0x11, 0xCC, 0x10, 0x1B, 0x13, 0xCC, 0x1F, 0x18, 0x11, 0x11, 0x1C, 0x1F}, 62, 172);
    int words = 0, in_word = 0, letters = 0;
    for (const char *p = text; *p; p++) {
        if (*p == ' ') { in_word = 0; }
        else { if (!in_word) { words++; in_word = 1; } letters++; }
    }
    printf(dec_44fa((const unsigned char[]){0xD1, 0x10, 0xCC, 0xD1, 0x10, 0xCC, 0xD1, 0x26, 0x21, 0xB6}, 10, 172), words, letters, strlen(text));
    return 0;
}
