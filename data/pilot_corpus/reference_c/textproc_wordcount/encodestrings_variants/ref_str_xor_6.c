#include <stdio.h>
#include <string.h>

static char dec_e5d0_buf[4][256];
static int dec_e5d0_slot = 0;
static const char *dec_e5d0(const unsigned char *enc, int n, int key) {
    int s = dec_e5d0_slot++ % 4;
    char *out = dec_e5d0_buf[s];
    for (int i = 0; i < n && i < 255; i++) out[i] = (char)(enc[i] ^ key);
    out[n < 255 ? n : 255] = '\0';
    return out;
}

int main(void) {
    const char *text = dec_e5d0((const unsigned char[]){0xF4, 0xE8, 0xE5, 0xA0, 0xF1, 0xF5, 0xE9, 0xE3, 0xEB, 0xA0, 0xE2, 0xF2, 0xEF, 0xF7, 0xEE, 0xA0, 0xE6, 0xEF, 0xF8, 0xA0, 0xEA, 0xF5, 0xED, 0xF0, 0xF3, 0xA0, 0xEF, 0xF6, 0xE5, 0xF2, 0xA0, 0xF4, 0xE8, 0xE5, 0xA0, 0xEC, 0xE1, 0xFA, 0xF9, 0xA0, 0xE4, 0xEF, 0xE7, 0xA0, 0xE1, 0xEE, 0xE4, 0xA0, 0xF4, 0xE8, 0xE5, 0xA0, 0xE4, 0xEF, 0xE7, 0xA0, 0xF3, 0xEC, 0xE5, 0xE5, 0xF0, 0xF3}, 62, 128);
    int words = 0, in_word = 0, letters = 0;
    for (const char *p = text; *p; p++) {
        if (*p == ' ') { in_word = 0; }
        else { if (!in_word) { words++; in_word = 1; } letters++; }
    }
    printf(dec_e5d0((const unsigned char[]){0xA5, 0xE4, 0xA0, 0xA5, 0xE4, 0xA0, 0xA5, 0xFA, 0xF5, 0x8A}, 10, 128), words, letters, strlen(text));
    return 0;
}
