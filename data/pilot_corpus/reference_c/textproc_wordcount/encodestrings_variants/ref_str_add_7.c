#include <stdio.h>
#include <string.h>

static char dec_d3e2_buf[4][256];
static int dec_d3e2_slot = 0;
static const char *dec_d3e2(const unsigned char *enc, int n, int key) {
    int s = dec_d3e2_slot++ % 4;
    char *out = dec_d3e2_buf[s];
    for (int i = 0; i < n && i < 255; i++) out[i] = (char)(enc[i] - key);
    out[n < 255 ? n : 255] = '\0';
    return out;
}

