#include <stdio.h>
#include <string.h>

static char dec_3dcc_buf[4][256];
static int dec_3dcc_slot = 0;
static const char *dec_3dcc(const unsigned char *enc, int n, int key) {
    int s = dec_3dcc_slot++ % 4;
    char *out = dec_3dcc_buf[s];
    for (int i = 0; i < n && i < 255; i++) out[i] = (char)(enc[i] - key);
    out[n < 255 ? n : 255] = '\0';
    return out;
}

int main(void) {
    const char *text = dec_3dcc((const unsigned char[]){0x8D, 0x81, 0x7E, 0x39, 0x8A, 0x8E, 0x82, 0x7C, 0x84, 0x39, 0x7B, 0x8B, 0x88, 0x90, 0x87, 0x39, 0x7F, 0x88, 0x91, 0x39, 0x83, 0x8E, 0x86, 0x89, 0x8C, 0x39, 0x88, 0x8F, 0x7E, 0x8B, 0x39, 0x8D, 0x81, 0x7E, 0x39, 0x85, 0x7A, 0x93, 0x92, 0x39, 0x7D, 0x88, 0x80, 0x39, 0x7A, 0x87, 0x7D, 0x39, 0x8D, 0x81, 0x7E, 0x39, 0x7D, 0x88, 0x80, 0x39, 0x8C, 0x85, 0x7E, 0x7E, 0x89, 0x8C}, 62, 25);
    int words = 0, in_word = 0, letters = 0;
    for (const char *p = text; *p; p++) {
        if (*p == ' ') { in_word = 0; }
        else { if (!in_word) { words++; in_word = 1; } letters++; }
    }
    printf(dec_3dcc((const unsigned char[]){0x3E, 0x7D, 0x39, 0x3E, 0x7D, 0x39, 0x3E, 0x93, 0x8E, 0x23}, 10, 25), words, letters, strlen(text));
    return 0;
}
