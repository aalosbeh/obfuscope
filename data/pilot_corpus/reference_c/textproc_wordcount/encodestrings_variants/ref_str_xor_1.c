#include <stdio.h>
#include <string.h>

static char dec_a99b_buf[4][256];
static int dec_a99b_slot = 0;
static const char *dec_a99b(const unsigned char *enc, int n, int key) {
    int s = dec_a99b_slot++ % 4;
    char *out = dec_a99b_buf[s];
    for (int i = 0; i < n && i < 255; i++) out[i] = (char)(enc[i] ^ key);
    out[n < 255 ? n : 255] = '\0';
    return out;
}

int main(void) {
    const char *text = dec_a99b((const unsigned char[]){0x32, 0x2E, 0x23, 0x66, 0x37, 0x33, 0x2F, 0x25, 0x2D, 0x66, 0x24, 0x34, 0x29, 0x31, 0x28, 0x66, 0x20, 0x29, 0x3E, 0x66, 0x2C, 0x33, 0x2B, 0x36, 0x35, 0x66, 0x29, 0x30, 0x23, 0x34, 0x66, 0x32, 0x2E, 0x23, 0x66, 0x2A, 0x27, 0x3C, 0x3F, 0x66, 0x22, 0x29, 0x21, 0x66, 0x27, 0x28, 0x22, 0x66, 0x32, 0x2E, 0x23, 0x66, 0x22, 0x29, 0x21, 0x66, 0x35, 0x2A, 0x23, 0x23, 0x36, 0x35}, 62, 70);
    int words = 0, in_word = 0, letters = 0;
    for (const char *p = text; *p; p++) {
        if (*p == ' ') { in_word = 0; }
        else { if (!in_word) { words++; in_word = 1; } letters++; }
    }
    printf(dec_a99b((const unsigned char[]){0x63, 0x22, 0x66, 0x63, 0x22, 0x66, 0x63, 0x3C, 0x33, 0x4C}, 10, 70), words, letters, strlen(text));
    return 0;
}
