#include <stdio.h>
#include <string.h>

static char dec_dc74_buf[4][256];
static int dec_dc74_slot = 0;
static const char *dec_dc74(const unsigned char *enc, int n, int key) {
    int s = dec_dc74_slot++ % 4;
    char *out = dec_dc74_buf[s];
    for (int i = 0; i < n && i < 255; i++) out[i] = (char)(enc[i] - key);
    out[n < 255 ? n : 255] = '\0';
    return out;
}

int main(void) {
    const char *text = dec_dc74((const unsigned char[]){0x3C, 0x30, 0x2D, 0xE8, 0x39, 0x3D, 0x31, 0x2B, 0x33, 0xE8, 0x2A, 0x3A, 0x37, 0x3F, 0x36, 0xE8, 0x2E, 0x37, 0x40, 0xE8, 0x32, 0x3D, 0x35, 0x38, 0x3B, 0xE8, 0x37, 0x3E, 0x2D, 0x3A, 0xE8, 0x3C, 0x30, 0x2D, 0xE8, 0x34, 0x29, 0x42, 0x41, 0xE8, 0x2C, 0x37, 0x2F, 0xE8, 0x29, 0x36, 0x2C, 0xE8, 0x3C, 0x30, 0x2D, 0xE8, 0x2C, 0x37, 0x2F, 0xE8, 0x3B, 0x34, 0x2D, 0x2D, 0x38, 0x3B}, 62, 200);
    int words = 0, in_word = 0, letters = 0;
    for (const char *p = text; *p; p++) {
        if (*p == ' ') { in_word = 0; }
        else { if (!in_word) { words++; in_word = 1; } letters++; }
    }
    printf(dec_dc74((const unsigned char[]){0xED, 0x2C, 0xE8, 0xED, 0x2C, 0xE8, 0xED, 0x42, 0x3D, 0xD2}, 10, 200), words, letters, strlen(text));
    return 0;
}
