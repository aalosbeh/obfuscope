#include <stdio.h>
#include <string.h>

static char dec_f6ca_buf[4][256];
static int dec_f6ca_slot = 0;
static const char *dec_f6ca(const unsigned char *enc, int n, int key) {
    int s = dec_f6ca_slot++ % 4;
    char *out = dec_f6ca_buf[s];
    for (int i = 0; i < n && i < 255; i++) out[i] = (char)(enc[i] ^ key);
    out[n < 255 ? n : 255] = '\0';
    return out;
}

