#include <stdio.h>
#include <string.h>

static char dec_5ccc_buf[4][256];
static int dec_5ccc_slot = 0;
static const char *dec_5ccc(const unsigned char *enc, int n, int key) {
    int s = dec_5ccc_slot++ % 4;
    char *out = dec_5ccc_buf[s];
    for (int i = 0; i < n && i < 255; i++) out[i] = (char)(enc[i] ^ key);
    out[n < 255 ? n : 255] = '\0';
    return out;
}

int main(void) {
    const char *text = dec_5ccc((const unsigned char[]){0x25, 0x39, 0x34, 0x71, 0x20, 0x24, 0x38, 0x32, 0x3A, 0x71, 0x33, 0x23, 0x3E, 0x26, 0x3F, 0x71, 0x37, 0x3E, 0x29, 0x71, 0x3B, 0x24, 0x3C, 0x21, 0x22, 0x71, 0x3E, 0x27, 0x34, 0x23, 0x71, 0x25, 0x39, 0x34, 0x71, 0x3D, 0x30, 0x2B, 0x28, 0x71, 0x35, 0x3E, 0x36, 0x71, 0x30, 0x3F, 0x35, 0x71, 0x25, 0x39, 0x34, 0x71, 0x35, 0x3E, 0x36, 0x71, 0x22, 0x3D, 0x34, 0x34, 0x21, 0x22}, 62, 81);
    int words = 0, in_word = 0, letters = 0;
    for (const char *p = text; *p; p++) {
        if (*p == ' ') { in_word = 0; }
        else { if (!in_word) { words++; in_word = 1; } letters++; }
    }
    printf(dec_5ccc((const unsigned char[]){0x74, 0x35, 0x71, 0x74, 0x35, 0x71, 0x74, 0x2B, 0x24, 0x5B}, 10, 81), words, letters, strlen(text));
    return 0;
}
